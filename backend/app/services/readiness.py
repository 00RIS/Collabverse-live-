"""
app/services/readiness.py

WHAT THIS FILE IS:
The Career Readiness Score calculation (spec Section 5) and the
skill-gap engine behind it. This is a PURE function — it takes plain
Python data in and returns plain Python data out, with no database
session, no FastAPI, no HTTP anywhere in it.

WHY IT'S A SEPARATE "SERVICE" FILE INSTEAD OF LIVING IN THE ENDPOINT:
The spec (Section 34, Testing) says: "Critical business logic should be
testable independently of the UI." If this calculation lived inside a
FastAPI endpoint function, testing it would require spinning up a
database, creating fake HTTP requests, etc. By keeping it a pure
function of "list of requirements" + "dict of student proficiencies",
we can write a plain unit test like:

    result = calculate_readiness(requirements=[...], student_skills={...})
    assert result.readiness_score == 75.0

with no database or web server involved at all. The API endpoint
(endpoints/careers.py) is a thin wrapper that fetches the data from
Postgres and calls this function.

WHY THIS IS "EXPLAINABLE" (spec: "Do not let an LLM invent this score"):
Every number in the output is derived by a fixed, inspectable formula —
not generated by a language model. Anyone can look at this file and
verify exactly why a student got 82% instead of 90%.

THE FORMULA:
For each required skill r (with required_proficiency R and importance
weight W), and the student's own proficiency P for that skill (0 if they
don't have it at all):

    ratio_r = min(P / R, 1.0)        # capped at 100% credit per skill —
                                       # exceeding the requirement doesn't
                                       # let one skill compensate for a
                                       # missing one elsewhere
    readiness_score = ( sum(W_r * ratio_r) / sum(W_r) ) * 100

Each requirement is also classified for the breakdown:
    - "strong"  if P >= R      (fully meets or exceeds what's required)
    - "partial" if 0 < P < R   (has some of the skill, not enough yet)
    - "missing" if P == 0      (student has never logged this skill)

"Priority gaps" are partial + missing requirements, sorted by
importance_weight descending — the idea being: fix the highest-weight
gap first for the biggest readiness-score improvement per unit of
effort.
"""

from dataclasses import dataclass


@dataclass
class RequirementInput:
    """One row of a career's skill requirements, already loaded from the DB."""
    skill_id: str
    skill_name: str
    required_proficiency: int
    importance_weight: float


@dataclass
class GapResult:
    skill_id: str
    skill_name: str
    required_proficiency: int
    student_proficiency: int
    importance_weight: float
    status: str  # "strong" | "partial" | "missing"


@dataclass
class ReadinessResult:
    readiness_score: float
    strong: list[GapResult]
    partial: list[GapResult]
    missing: list[GapResult]
    priority_gaps: list[GapResult]
    recommended_actions: list[str]


def calculate_readiness(
    requirements: list[RequirementInput],
    student_proficiencies: dict[str, int],
    max_recommendations: int = 3,
) -> ReadinessResult:
    """
    `student_proficiencies` maps skill_id -> proficiency level (1-4) for
    every skill the student has logged. A skill the student has never
    added simply won't be a key in this dict, which is why we use
    `.get(skill_id, 0)` below — no entry means proficiency 0.
    """
    if not requirements:
        # A career with no defined requirements yet has no meaningful
        # score. Returning 0 (rather than crashing on a division by
        # zero) keeps the API well-behaved while the requirement list is
        # still being built out by an institution/admin.
        return ReadinessResult(0.0, [], [], [], [], [])

    weighted_ratio_sum = 0.0
    total_weight = 0.0
    gaps: list[GapResult] = []

    for req in requirements:
        student_level = student_proficiencies.get(req.skill_id, 0)
        ratio = min(student_level / req.required_proficiency, 1.0) if req.required_proficiency > 0 else 1.0

        weighted_ratio_sum += req.importance_weight * ratio
        total_weight += req.importance_weight

        if student_level >= req.required_proficiency:
            status = "strong"
        elif student_level > 0:
            status = "partial"
        else:
            status = "missing"

        gaps.append(
            GapResult(
                skill_id=req.skill_id,
                skill_name=req.skill_name,
                required_proficiency=req.required_proficiency,
                student_proficiency=student_level,
                importance_weight=req.importance_weight,
                status=status,
            )
        )

    readiness_score = round((weighted_ratio_sum / total_weight) * 100, 1) if total_weight > 0 else 0.0

    strong = [g for g in gaps if g.status == "strong"]
    partial = [g for g in gaps if g.status == "partial"]
    missing = [g for g in gaps if g.status == "missing"]

    priority_gaps = sorted(partial + missing, key=lambda g: g.importance_weight, reverse=True)

    recommended_actions = [
        f"Improve '{g.skill_name}' from level {g.student_proficiency} toward the required level "
        f"{g.required_proficiency} — this is one of the highest-weighted gaps for this career."
        if g.status == "partial"
        else f"Start building '{g.skill_name}' (currently not on your profile at all) — "
        f"required at level {g.required_proficiency} for this career."
        for g in priority_gaps[:max_recommendations]
    ]

    return ReadinessResult(
        readiness_score=readiness_score,
        strong=strong,
        partial=partial,
        missing=missing,
        priority_gaps=priority_gaps,
        recommended_actions=recommended_actions,
    )
